"""Fixed evaluation contract: eps, dtypes, seeds, shapes, tolerances, cases.

Do not let the agent edit this file. Changing anything here invalidates
comparisons with earlier rows of results.tsv, so CONTRACT_VERSION is recorded
with every row.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import torch

CONTRACT_VERSION = "rmsnorm-v2"  # v2: + aggregate relative-RMS bound

# ---- RMSNorm operator contract -------------------------------------------
# y = x * rsqrt(mean(x^2, -1) + eps) * weight
# x, weight: fp16. Reduction and intermediates: fp32. y: fp16.
EPS = 1e-6
IN_DTYPE = torch.float16
OUT_DTYPE = torch.float16

# Accuracy: |y - ref| <= ATOL + RTOL * |ref|, elementwise, ref rounded to fp16.
# fp16 has ~1e-3 relative precision; HVX rsqrt/div and a different fp32
# summation order add a little more. The official hexagon-mlir rms_norm test
# uses atol=1e-2.
ATOL = 1e-2
RTOL = 1e-2
# Aggregate bound: ||y - ref||_2 / ||ref||_2. Elementwise atol/rtol alone let a
# systematic ~1% scale error through (found in exp hos0016: dividing by the
# padded block size instead of H passed on 3x4000 and 2x1000). fp16 output
# rounding alone gives ~3e-4.
REL_RMS_MAX = 2e-3

# ---- Performance cases -----------------------------------------------------
PRIMARY_SHAPE = (1, 4096)  # LLM decode; primary adoption metric = DSP time here
PERF_SHAPES = [(1, 4096), (32, 4096)]
PERF_SEED = 0

# Weight generator (same for every case, seeded separately)
WEIGHT_SEED = 1234


@dataclass(frozen=True)
class Case:
    name: str
    shape: tuple
    kind: str  # randn | zeros | small | large | mixed
    seed: int
    needs_tail: bool = False  # H not a multiple of the HVX vector (64 x fp16)
    perf: bool = False


def perf_cases(shapes=None) -> list[Case]:
    shapes = shapes or PERF_SHAPES
    return [Case(f"perf_{m}x{h}", (m, h), "randn", PERF_SEED, perf=True) for m, h in shapes]


def validation_cases() -> list[Case]:
    """Hidden-from-perf validation inputs, generated by the evaluator."""
    cases = []
    for seed in (11, 12, 13):
        cases.append(Case(f"val_randn_s{seed}_1x4096", (1, 4096), "randn", seed))
    cases.append(Case("val_randn_s14_32x4096", (32, 4096), "randn", 14))
    cases.append(Case("val_zeros_1x4096", (1, 4096), "zeros", 0))
    cases.append(Case("val_small_1x4096", (1, 4096), "small", 21))
    cases.append(Case("val_large_1x4096", (1, 4096), "large", 22))
    cases.append(Case("val_mixed_4x4096", (4, 4096), "mixed", 23))
    # tail handling: H not a multiple of 64 and not a power of two
    cases.append(Case("val_tail_3x4000", (3, 4000), "randn", 31, needs_tail=True))
    cases.append(Case("val_tail_1x4100", (1, 4100), "randn", 32, needs_tail=True))
    cases.append(Case("val_tail_2x1000", (2, 1000), "randn", 33, needs_tail=True))
    return cases


def make_inputs(case: Case):
    m, h = case.shape
    g = torch.Generator().manual_seed(case.seed)
    if case.kind == "randn":
        x = torch.randn(m, h, generator=g)
    elif case.kind == "zeros":
        x = torch.zeros(m, h)
    elif case.kind == "small":
        # x^2 ~ 1e-8 per element, so eps (1e-6) dominates the denominator
        x = torch.randn(m, h, generator=g) * 1e-4
    elif case.kind == "large":
        # near fp16 max: x^2 overflows fp16 (6.5e4) -> catches fp16 reductions
        x = (torch.randn(m, h, generator=g) * 2.0e4).clamp(-6.0e4, 6.0e4)
    elif case.kind == "mixed":
        scales = torch.tensor([1e-3, 1.0, 1e2, 3e4])[:m].reshape(m, 1)
        x = (torch.randn(m, h, generator=g) * scales).clamp(-6.0e4, 6.0e4)
    else:
        raise ValueError(case.kind)
    x = x.to(IN_DTYPE)
    gw = torch.Generator().manual_seed(WEIGHT_SEED)
    w = (1.0 + 0.1 * torch.randn(h, generator=gw)).to(IN_DTYPE)
    return x.contiguous(), w.contiguous()


@dataclass
class AccuracyResult:
    case: str
    ok: bool
    max_abs_err: float | None
    max_rel_err: float | None
    n_bad: int = 0
    note: str = ""
    worst_index: tuple | None = None
    extra: dict = field(default_factory=dict)


def check(case: Case, y: torch.Tensor, ref: torch.Tensor) -> AccuracyResult:
    if y is None:
        return AccuracyResult(case.name, False, None, None, note="no output")
    if tuple(y.shape) != tuple(ref.shape):
        return AccuracyResult(case.name, False, None, None, note=f"shape {tuple(y.shape)} != {tuple(ref.shape)}")
    if y.dtype != OUT_DTYPE:
        return AccuracyResult(case.name, False, None, None, note=f"dtype {y.dtype} != {OUT_DTYPE}")
    yf, rf = y.float(), ref.float()
    nonfinite = (~torch.isfinite(yf)).sum().item()
    diff = (yf - rf).abs()
    diff = torch.where(torch.isfinite(diff), diff, torch.full_like(diff, float("inf")))
    bad = diff > (ATOL + RTOL * rf.abs())
    max_abs = diff.max().item()
    rel = diff / rf.abs().clamp_min(1e-6)
    idx = tuple(int(i) for i in torch.nonzero(diff == diff.max())[0].tolist())
    note = f"{nonfinite} non-finite outputs" if nonfinite else ""
    ref_norm = rf.norm().item()
    rel_rms = (diff.norm().item() / ref_norm) if ref_norm > 1e-6 else None
    ok = not bool(bad.any())
    if rel_rms is not None and not rel_rms <= REL_RMS_MAX:
        ok = False
        note = (note + "; " if note else "") + f"rel_rms_err={rel_rms:.2e} > {REL_RMS_MAX:g}"
    return AccuracyResult(case.name, ok, max_abs, rel.max().item(),
                          int(bad.sum().item()), note, idx, {"rel_rms_err": rel_rms})
